"""Common-amplitude transfer of a property surface between electronic bases.

The model is defined in a fixed rectilinear reference coordinate system y:
  P_comp(y) - P_comp(0) = c [P_small(y) - P_small(0)] + delta_J y,
where delta_J = J_large - c J_small. Thus the first derivative is exactly
J_large and higher derivatives are c times the original derivatives. A
nonlinear coordinate transformation is applied to this complete surface,
including the curvature terms generated by delta_J. The common amplitude is
a local transfer assumption, not a convergence guarantee for higher ranks.
"""

import numpy as np

from .curvilinear_rechart import rechart_property_derivatives
from .gvpt2_spectroscopy import SonicPropertyDerivatives


def transport_cartesian_dipole_derivatives(first, atom_map, rotation):
    """Transport a Cartesian dipole Jacobian to a reordered, rotated frame.

    ``atom_map`` gives source atom indices in target order (zero based).
    Row coordinates satisfy x_target = x_source @ rotation. Both the polar
    vector components and the nuclear displacement axes are transformed.
    Translation has no effect on derivatives for a fixed molecular charge.
    """
    first = np.asarray(first, dtype=float)
    indices = np.asarray(atom_map)
    rotation = np.asarray(rotation, dtype=float)
    n = len(indices)
    if (indices.ndim != 1 or not np.issubdtype(indices.dtype, np.integer)
            or sorted(indices.tolist()) != list(range(n))):
        raise ValueError("bijective zero-based atom correspondence required")
    if first.shape != (3, 3 * n) or not np.all(np.isfinite(first)):
        raise ValueError("finite Cartesian dipole Jacobian of shape (3, 3N) required")
    if (rotation.shape != (3, 3) or not np.all(np.isfinite(rotation))
            or not np.allclose(rotation.T @ rotation, np.eye(3), atol=1e-10, rtol=0)
            or not np.isclose(np.linalg.det(rotation), 1., atol=1e-10, rtol=0)):
        raise ValueError("a proper orthogonal rotation is required")
    reordered = first.reshape(3, n, 3)[:, indices, :]
    return np.einsum("ab,bic,cd->aid", rotation.T, reordered, rotation).reshape(3, 3*n)


def fit_common_property_scale(first_small, first_large, *, projector=None):
    """Fit one positive real amplitude in a declared common modal subspace.

    An orthogonal projector selects the calibration subspace without assigning
    ratios to individual modes or dividing by symmetry-forbidden derivatives.
    The Frobenius fit is invariant under orthogonal changes of the common
    property-component and coordinate frames, with the projector transported.
    """
    small, large = np.asarray(first_small), np.asarray(first_large)
    if small.ndim < 1 or large.shape != small.shape:
        raise ValueError("matching property first-derivative arrays required")
    if not np.all(np.isfinite(small)) or not np.all(np.isfinite(large)):
        raise ValueError("finite property derivatives required")
    n = small.shape[-1]
    p = np.eye(n) if projector is None else np.asarray(projector, float)
    if (p.shape != (n, n) or not np.all(np.isfinite(p))
            or not np.allclose(p, p.T, atol=1e-10, rtol=1e-10)
            or not np.allclose(p @ p, p, atol=1e-10, rtol=1e-10)):
        raise ValueError("an orthogonal coordinate projector is required")
    left, right = small @ p, large @ p
    denominator = float(np.vdot(left, left).real)
    norm_large = float(np.linalg.norm(right))
    if denominator <= 0 or norm_large == 0:
        raise ValueError("nonzero derivatives in the calibration subspace required")
    scale = float(np.vdot(left, right).real / denominator)
    if not np.isfinite(scale) or scale <= 0:
        raise ValueError("common positive amplitude is incompatible with the supplied frames")
    return scale, {
        "projector_rank": int(round(np.trace(p))),
        "relative_first_derivative_residual": float(
            np.linalg.norm(right - scale * left) / norm_large
        ),
        "first_derivative_norm_ratio": float(norm_large / np.sqrt(denominator)),
        "scale_source": "least squares of first derivatives; no spectral observations",
    }


def linear_matched_basis_transfer(
    small, first_large, scale, *, inverse_second=None, inverse_third=None
):
    """Transfer in rectilinear source coordinates, then transform if requested.

    All input derivatives use the same native coordinate and property frames.
    Oscillator normalization is applied separately, after this transformation.
    The factor multiplies each higher derivative once, irrespective of rank.
    """
    first_large = np.asarray(first_large)
    if not np.isfinite(scale) or scale <= 0:
        raise ValueError("positive finite property amplitude required")
    first, second, third = map(np.asarray, (small.first, small.second, small.third))
    if first.ndim < 1:
        raise ValueError("a property first derivative is required")
    n = first.shape[-1]
    if (first_large.shape != first.shape
            or second.shape != first.shape[:-1] + (n, n)
            or third.shape != first.shape[:-1] + (n, n, n)
            or any(not np.all(np.isfinite(x)) for x in (first, first_large, second, third))):
        raise ValueError("finite derivatives through rank three in a common frame required")
    values = (first_large.copy(), scale * second, scale * third)
    if (inverse_second is None) != (inverse_third is None):
        raise ValueError("both inverse coordinate derivatives are required")
    if inverse_second is not None:
        values = rechart_property_derivatives(
            *values, inverse_second, inverse_third
        )
    return SonicPropertyDerivatives(*values)
