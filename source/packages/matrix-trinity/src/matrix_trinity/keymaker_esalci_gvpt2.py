def run_esalci_gvpt2_protocol(
    *,
    atomic_numbers: np.ndarray,
    masses_amu: np.ndarray,
    frozen_esalci_b: np.ndarray,
    geometry_at_s: Callable[[np.ndarray], np.ndarray],
    evaluator: Callable[[np.ndarray], object],
    metric_first_at_s: Callable[[np.ndarray], np.ndarray] | None = None,
    b_matrix_at_s: Callable[[np.ndarray], np.ndarray] | None = None,
    b_prime_cartesian_at_s: Callable[[np.ndarray], np.ndarray] | None = None,
    analytic_eckart_chart: bool = False,
    eckart_full_metric_prime: bool = False,
    mode_contribution_cache: object | None = None,
    dipole_at_s: Callable[[np.ndarray], np.ndarray] | None = None,
    dipole_symmetry_operations: tuple[tuple[np.ndarray, np.ndarray], ...] = (),
    reference_symmetry_operations: tuple[tuple[np.ndarray, np.ndarray], ...] = (),
    modal_dipole_derivatives: (
        SonicPropertyDerivatives
        | Callable[[np.ndarray, np.ndarray], SonicPropertyDerivatives]
        | None
    ) = None,
    polarizability_gradient_at_s: Callable[[np.ndarray], np.ndarray] | None = None,
    magnetic_dipole_derivatives: SonicMomentumPropertyDerivatives | None = None,
    roa_response_derivatives: SonicROAPropertySurfaces | None = None,
    gaussian_aat_at_s: Callable[[np.ndarray], np.ndarray] | None = None,
    gaussian_roa_gradients_at_s: Callable[[np.ndarray], tuple[np.ndarray, np.ndarray, np.ndarray]] | None = None,
    roa_incident_frequency_au: float | None = None,
    step_dimensionless: float = 0.08,
    step_mass_weighted_angstrom: float | None = None,
    cubic_estimator_policy: str = "hessian_gradient_mean",
    force_constant_cutoff_au: float = 0.0,
    final_force_constant_cutoff_au: float | None = None,
    dipole_step_dimensionless: float = 0.12,
    geometry_derivative_step_s: float = 1e-4,
    rotational_dof: int = 3,
    gf_frequency_tolerance_cm: float = 0.5,
    harmonic_identity_required: bool = False,
    spectrum_state_policy: str = "all",
    max_quanta: int = 4,
    max_states: int = 30000,
    resonance_policy: str = "auto",
    resonance_criteria: Mapping[str, float] | None = None,
    fermi_basis_policy: str = "complete",
    polyad_selection_policy: str = "adaptive",
    polyad_target_max_quanta: int = 2,
    polyad_target_states: tuple[tuple[int, ...], ...] | None = None,
    polyad_spectral_window_cm: tuple[float, float] | None = None,
    polyad_energy_tolerance_cm: float = 0.1,
    polyad_ir_tolerance_km_mol: float = 0.1,
    polyad_max_expansions: int = 12,
    polyad_excluded_modes: tuple[int, ...] = (),
    polyad_max_total_quanta: int = 4,
    polyad_max_mode_quanta: int = 4,
    targeted_polyad_options: Mapping[str, object] | None = None,
    quartic_policy: str = "complete",
    include_rovibrational: bool = True,
    property_workers: int = 0,
) -> ESALCIGVPT2ProtocolResult:
    """Execute the ESALC-I normal-mode GVPT2 spectroscopy protocol.

    ``geometry_at_s`` is the nonlinear, body-fixed realization of a *frozen*
    nonredundant ESALC-I/SONIC chart, in bohr. ``frozen_esalci_b`` is its
    equilibrium Wilson B matrix in inverse bohr. The backend receives Cartesian
    angstrom and supplies Cartesian gradient and Hessian. The dipole provider
    supplies either a Cartesian Jacobian in atomic units per bohr or values via
    ``dipole_at_s``. When full-precision modal D1/D2/D3 from the same electronic
    calculation are available, ``modal_dipole_derivatives`` takes precedence.
    Otherwise the equilibrium evaluator result may supply that same attribute;
    only when neither does the protocol reconstruct D1/D2/D3 from stencils.
    A callback receives the acquired SONIC displacement matrix and frequencies,
    and returns tensors in that dimensionless mode basis and the fixed Cartesian
    dipole frame. Their original chart and mode order are preserved
    over the Hessian, metric and dipole stencils. The single-mode policy
    uses only one-mode displacements and Fermi resonances.
    ``step_mass_weighted_angstrom=0.01`` selects the GDV normal-mode
    displacement; the backend must keep the reference Cartesian frame fixed
    across all displaced electronic calculations.
    ``dipole_symmetry_operations`` projects dipole values at their source,
    before any finite differences; supply every nonidentity operation of the
    molecular point group as (ESALC chart action, Cartesian vector action).
    ``reference_symmetry_operations`` supplies the corresponding Cartesian
    actions. The driver symmetrizes every Hessian and projects each electronic
    point over the operations that leave its displaced geometry invariant.
    """
    atoms = np.asarray(atomic_numbers, dtype=int).reshape(-1)
    masses = np.asarray(masses_amu, dtype=float).reshape(-1)
    b = np.asarray(frozen_esalci_b, dtype=float)
    n = b.shape[0] if b.ndim == 2 else 0
    if (len(atoms) < 2 or len(masses) != len(atoms) or np.any(atoms <= 0)
            or not np.all(np.isfinite(masses)) or np.any(masses <= 0)
            or b.shape != (3 * len(atoms) - 3 - rotational_dof, 3 * len(atoms))
            or n < 1 or not np.all(np.isfinite(b))
            or np.linalg.matrix_rank(b) != n):
        raise ValueError("ESALC-I protocol requires a complete nonredundant frozen B matrix")
    if not np.isfinite(gf_frequency_tolerance_cm) or gf_frequency_tolerance_cm <= 0:
        raise ValueError("GF frequency tolerance must be positive")
    if spectrum_state_policy not in {"all", "fundamentals_polyads"}:
        raise ValueError("unsupported GVPT2 spectrum state policy")
    if polyad_selection_policy not in {"fixed", "adaptive"}:
        raise ValueError("unsupported polyad selection policy")
    if (len(set(polyad_excluded_modes)) != len(polyad_excluded_modes)
            or any(mode < 0 or mode >= n for mode in polyad_excluded_modes)
            or polyad_max_total_quanta < polyad_target_max_quanta
            or polyad_max_mode_quanta < 1):
        raise ValueError("invalid excluded modes or polyad quantum limits")
    if polyad_target_states is not None and any(
        len(state) != n or any(value < 0 for value in state)
        or any(state[mode] for mode in polyad_excluded_modes)
        or sum(state) > polyad_max_total_quanta
        or max(state) > polyad_max_mode_quanta
        for state in polyad_target_states
    ):
        raise ValueError("invalid requested polyad target state")
    if polyad_selection_policy == "adaptive" and spectrum_state_policy != "all":
        raise ValueError("adaptive polyad targets require the complete requested spectrum")
    if max_quanta < 2 or max_states < 1:
        raise ValueError("GVPT2 requires at least two quanta and a positive state cap")
    if not isinstance(property_workers, int) or property_workers < 0:
        raise ValueError("property workers must be a nonnegative integer")
    if fermi_basis_policy not in {"complete", "tars_auto"}:
        raise ValueError("unsupported GVPT2 basis policy")
    if (fermi_basis_policy == "tars_auto"
            and (max_quanta != 2 or resonance_policy not in {"fermi_auto", "gdv"})):
        raise ValueError("screened GVPT2 basis requires two quanta and Fermi-auto or GDV resonances")
    if (polyad_selection_policy == "fixed" and fermi_basis_policy == "complete"
            and comb(n - len(polyad_excluded_modes) + max_quanta, max_quanta)
            + len(polyad_excluded_modes) > max_states):
        raise ValueError(
            "complete GVPT2 basis exceeds max_states before electronic acquisition: "
            f"{comb(n - len(polyad_excluded_modes) + max_quanta, max_quanta) + len(polyad_excluded_modes)} "
            f"states for {n - len(polyad_excluded_modes)} polyad modes; "
            "raise max_states or select a screened basis"
        )
    if (polyad_selection_policy == "adaptive"
            and (polyad_target_max_quanta not in {2, 3}
                 or (polyad_target_states is None and polyad_spectral_window_cm is None
                     and comb(n - len(polyad_excluded_modes) + polyad_target_max_quanta,
                              polyad_target_max_quanta)
                     + len(polyad_excluded_modes) > max_states)
                 or (polyad_target_states is not None
                     and len(polyad_target_states) + n + 1 > max_states))):
        raise ValueError("adaptive target manifold exceeds max_states before electronic acquisition")
    if dipole_symmetry_operations and modal_dipole_derivatives is not None:
        raise ValueError("source symmetry projection requires a property evaluator")
    if quartic_policy not in {"semidiagonal", "semidiagonal_analytic_metric", "complete"}:
        raise ValueError("quartic policy must be semidiagonal, semidiagonal_analytic_metric or complete")
    if quartic_policy != "complete" and resonance_policy not in {"fermi_auto", "none"}:
        raise ValueError("semidiagonal quartic field requires Fermi-only resonance treatment")
    if (quartic_policy == "semidiagonal_analytic_metric" and metric_first_at_s is None
            and (b_matrix_at_s is None or b_prime_cartesian_at_s is None)):
        raise ValueError("analytic-metric protocol requires G prime or both B and B prime providers")
    h = float(geometry_derivative_step_s)
    if not np.isfinite(h) or h <= 0:
        raise ValueError("ESALC-I geometry derivative step must be positive")

    def geometry(s: np.ndarray) -> np.ndarray:
        xyz = np.asarray(geometry_at_s(np.asarray(s, dtype=float)), dtype=float)
        if xyz.shape != (len(atoms), 3) or not np.all(np.isfinite(xyz)):
            raise ValueError("ESALC-I chart returned invalid Cartesian bohr geometry")
        return xyz

    zero = np.zeros(n)
    reference_geometry = geometry(zero)
    reference_actions = []
    for cartesian_action, vector_action in reference_symmetry_operations:
        action = np.asarray(cartesian_action, dtype=float)
        vector = np.asarray(vector_action, dtype=float)
        size = 3 * len(atoms)
        if (action.shape != (size, size) or vector.shape != (3, 3)
                or not np.allclose(action.T @ action, np.eye(size), atol=1e-8)
                or not np.allclose(vector.T @ vector, np.eye(3), atol=1e-8)
                or np.max(abs(action @ reference_geometry.ravel()
                                  - reference_geometry.ravel())) > 2e-5):
            raise ValueError("reference symmetry action must preserve the geometry")
        reference_actions.append((action, vector))
    if analytic_eckart_chart and b_matrix_at_s is not None:
        centered = reference_geometry - np.average(
            reference_geometry, axis=0, weights=masses,
        )
        rigid_constraints = np.zeros((6, 3 * len(atoms)))
        for atom, mass in enumerate(masses):
            rigid_constraints[:3, 3 * atom:3 * atom + 3] = mass * np.eye(3)
            for axis in range(3):
                rigid_constraints[3 + axis, 3 * atom:3 * atom + 3] = (
                    mass * np.cross(np.eye(3)[axis], centered[atom])
                )
        tangent_rhs = np.vstack((np.eye(n), np.zeros((6, n))))
    cache: dict[bytes, object] = {}

    def evaluate_xyz(xyz_angstrom: np.ndarray) -> object:
        xyz_bohr = np.asarray(xyz_angstrom, dtype=float) / BOHR_TO_ANGSTROM
        key = np.ascontiguousarray(xyz_bohr).tobytes()
        if key not in cache:
            value = evaluator(xyz_angstrom)
            raw_hessian = np.asarray(value.hessian_hartree_per_bohr2, dtype=float)
            if raw_hessian.shape != (3 * len(atoms),) * 2 or not np.all(np.isfinite(raw_hessian)):
                raise ValueError("Cartesian evaluator returned an invalid Hessian")
            sym_hessian = 0.5 * (raw_hessian + raw_hessian.T)
            value = _ProjectedReference(
                value, np.asarray(value.gradient_hartree_per_bohr, dtype=float).reshape(-1),
                sym_hessian, getattr(value, "dipole_derivatives_au_per_bohr", None),
            )
            # A displaced structure retains exactly the stabilizer of its
            # displacement within the reference point group.  Project at
            # that structure before any Cartesian-to-SONIC transformation;
            # operations taking it to a distinct structure are not members
            # of its point group and must not be applied here.
            stabilizer = [
                (action, vector) for action, vector in reference_actions
                if np.max(abs(action @ (xyz_bohr - reference_geometry).ravel()
                              - (xyz_bohr - reference_geometry).ravel())) < 1e-8
            ]
            if stabilizer:
                gradient = np.asarray(value.gradient_hartree_per_bohr, dtype=float).reshape(-1)
                hessian = np.asarray(value.hessian_hartree_per_bohr2, dtype=float)
                original_dipole = getattr(value, "dipole_derivatives_au_per_bohr", None)
                dipole_jacobian = (None if original_dipole is None else
                                   np.asarray(original_dipole, dtype=float).reshape(3, -1).copy())
                original_dipole_matrix = None if dipole_jacobian is None else dipole_jacobian.copy()
                projected_gradient = gradient.copy()
                projected_hessian = hessian.copy()
                for action, vector in stabilizer:
                    projected_gradient += action.T @ gradient
                    projected_hessian += action.T @ hessian @ action
                    if dipole_jacobian is not None:
                        dipole_jacobian += vector.T @ original_dipole_matrix @ action
                scale = 1 + len(stabilizer)
                projected_hessian /= scale
                projected_hessian = 0.5 * (projected_hessian + projected_hessian.T)
                value = _ProjectedReference(
                    value, projected_gradient / scale, projected_hessian,
                    None if dipole_jacobian is None else dipole_jacobian / scale,
                )
            cache[key] = value
        return cache[key]

    def evaluate(s: np.ndarray) -> object:
        return evaluate_xyz(geometry(s) * BOHR_TO_ANGSTROM)

    def tangent(s: np.ndarray) -> np.ndarray:
        if analytic_eckart_chart and b_matrix_at_s is not None:
            current_b = np.asarray(b_matrix_at_s(s), dtype=float)
            if current_b.shape != b.shape or not np.all(np.isfinite(current_b)):
                raise ValueError("analytic Eckart B matrix has invalid shape or values")
            return np.linalg.solve(
                np.vstack((current_b, rigid_constraints)), tangent_rhs,
            )
        columns = []
        for mode in range(n):
            delta = np.zeros(n)
            delta[mode] = h
            columns.append(((geometry(s + delta) - geometry(s - delta)) / (2 * h)).reshape(-1))
        return np.column_stack(columns)

    chart_residual = np.max(abs(b @ tangent(zero) - np.eye(n)))
    if chart_residual > 1e-4:
        raise ValueError("frozen ESALC-I B matrix and nonlinear chart disagree")
    first = evaluate(zero)
    cart_hessian = np.asarray(first.hessian_hartree_per_bohr2, dtype=float)
    cart_gradient = np.asarray(first.gradient_hartree_per_bohr, dtype=float).reshape(-1)
    if (cart_hessian.shape != (3 * len(atoms),) * 2
            or cart_gradient.shape != (3 * len(atoms),)
            or not np.all(np.isfinite(cart_hessian))
            or not np.all(np.isfinite(cart_gradient))
            or not np.allclose(cart_hessian, cart_hessian.T, rtol=1e-8, atol=1e-10)):
        raise ValueError("Cartesian evaluator lacks a valid gradient or Hessian")
    if analytic_eckart_chart:
        from matrix_smith import eckart_projected_b_matrix

        harmonic_b = eckart_projected_b_matrix(b, masses, rigid_constraints)
    else:
        harmonic_b = b
    harmonic_gf = gf_from_cartesian_hessian_and_gic_b_matrix(
        cart_hessian, harmonic_b, masses,
        gic_labels=tuple(f"ESALC-I-{i + 1}" for i in range(n)),
        coordinate_source="frozen-ESALC-I-KeyMaker",
    )

    acquired = acquire_sonic_vpt2_from_cartesian_evaluator(
        geometry_at_s=geometry, masses_amu=masses,
        evaluator=evaluate_xyz,
        metric_first_at_s=(metric_first_at_s
                           if quartic_policy == "semidiagonal_analytic_metric" else None),
        b_matrix_at_s=(b_matrix_at_s
                       if quartic_policy == "semidiagonal_analytic_metric" else None),
        b_prime_cartesian_at_s=(b_prime_cartesian_at_s
                                if quartic_policy == "semidiagonal_analytic_metric" else None),
        analytic_eckart_chart=analytic_eckart_chart,
        eckart_full_metric_prime=eckart_full_metric_prime,
        mode_contribution_cache=mode_contribution_cache,
        coordinate_count=n, step_dimensionless=step_dimensionless,
        step_mass_weighted_angstrom=step_mass_weighted_angstrom,
        cubic_estimator_policy=cubic_estimator_policy,
        force_constant_cutoff_au=force_constant_cutoff_au,
        final_force_constant_cutoff_au=final_force_constant_cutoff_au,
        geometry_derivative_step_s=h, rotational_dof=rotational_dof,
        complete_quartic=quartic_policy == "complete",
        fermi_only=quartic_policy != "complete",
        single_mode_only=quartic_policy != "complete", return_field=True,
    )
    if not isinstance(acquired, SonicAcquiredField):
        raise RuntimeError("ESALC-I protocol did not acquire the complete GVPT2 field")
    gvpt2 = (solve_sonic_gvpt2(
        acquired.field, max_quanta=max_quanta, max_states=max_states,
        resonance_policy=resonance_policy, fermi_basis_policy=fermi_basis_policy,
        resonance_criteria=resonance_criteria,
        polyad_excluded_modes=polyad_excluded_modes,
        max_mode_quanta=polyad_max_mode_quanta,
        targeted_polyad_options=targeted_polyad_options,
    ) if polyad_selection_policy == "fixed" else None)
    acquired_frequencies = (gvpt2.frequencies_cm if gvpt2 is not None
                            else _modalize_sonic_field(acquired.field)[0])
    residual = float(np.max(abs(np.sort(harmonic_gf.frequencies_cm)
                                - np.sort(acquired_frequencies))))
    if residual > gf_frequency_tolerance_cm:
        raise ValueError(f"ESALC-I GF and displaced-chart modes disagree by {residual:.3f} cm-1")

    transform = np.asarray(acquired.acquisition["sonic_displacements_per_dimensionless_mode"],
                           dtype=float)
    mode_steps = np.asarray(acquired.acquisition["mode_steps_dimensionless"], dtype=float)

    modal_source = (modal_dipole_derivatives if modal_dipole_derivatives is not None
                    else getattr(first, "modal_dipole_derivatives", None))
    if modal_source is not None:
        if dipole_at_s is not None:
            raise ValueError("provide either modal dipole derivatives or dipole values")
        supplied = (modal_source(
            transform.copy(), np.asarray(acquired_frequencies, dtype=float).copy(),
        ) if callable(modal_source) else modal_source)
        if not isinstance(supplied, SonicPropertyDerivatives):
            raise ValueError("modal dipole provider must return SonicPropertyDerivatives")
        tensors = (supplied.first, supplied.second, supplied.third)
        shapes = ((3, n), (3, n, n), (3, n, n, n))
        if any(value is None or np.asarray(value).shape != shape
               or not np.all(np.isfinite(value))
               for value, shape in zip(tensors, shapes)):
            raise ValueError("full-precision modal dipole derivatives require finite D1/D2/D3")
        dipole = SonicPropertyDerivatives(*(np.asarray(value, dtype=float) for value in tensors))
        cartesian_d1 = getattr(first, "dipole_derivatives_au_per_bohr", None)
        if cartesian_d1 is not None:
            expected_first = np.asarray(cartesian_d1, dtype=float) @ tangent(zero) @ transform
            if not np.allclose(dipole.first, expected_first, rtol=1e-5, atol=1e-7):
                raise ValueError("modal dipole derivatives disagree with the reference mode gauge")
    elif dipole_at_s is None:
        def dipole_jacobian(s: np.ndarray) -> np.ndarray:
            value = evaluate(s)
            derivative = np.asarray(value.dipole_derivatives_au_per_bohr, dtype=float)
            if derivative.shape != (3, 3 * len(atoms)) or not np.all(np.isfinite(derivative)):
                raise ValueError("Cartesian evaluator must provide a finite 3 x 3N dipole Jacobian")
            return derivative @ tangent(np.asarray(s, dtype=float))

        projected_dipole_jacobian = symmetry_project_dipole_jacobian(
            dipole_jacobian, dipole_symmetry_operations, n,
        )
        dipole = acquire_modal_property_derivatives_from_gradients(
            projected_dipole_jacobian, transform, component_count=3,
            step_dimensionless=mode_steps,
            single_mode_only=quartic_policy != "complete",
        )
    else:
        dipole = dipole_derivatives_from_values(
            dipole_at_s, transform, step_dimensionless=dipole_step_dimensionless,
            single_mode_only=quartic_policy != "complete",
            symmetry_operations=dipole_symmetry_operations,
        )
    if polarizability_gradient_at_s is None and hasattr(first, "polarizability_derivatives_au_per_bohr"):
        def polarizability_gradient_at_s(s: np.ndarray) -> np.ndarray:
            value = evaluate(s)
            derivative = np.asarray(value.polarizability_derivatives_au_per_bohr, dtype=float)
            if derivative.shape != (6, 3 * len(atoms)) or not np.all(np.isfinite(derivative)):
                raise ValueError("Cartesian evaluator must provide a finite 6 x 3N polarizability Jacobian")
            from .raman_derivatives import validate_cartesian_polarizability_jacobian
            validate_cartesian_polarizability_jacobian(derivative)
            return derivative @ tangent(np.asarray(s, dtype=float))

    if polarizability_gradient_at_s is not None:
        polarizability_gradient_at_s = _symmetry_project_property_jacobian(
            polarizability_gradient_at_s, dipole_symmetry_operations, n, 6,
            rank=2, voigt=True,
        )
    polarizability = (
        acquire_modal_property_derivatives_from_gradients(
            polarizability_gradient_at_s, transform, component_count=6,
            step_dimensionless=mode_steps,
            single_mode_only=quartic_policy != "complete",
        ) if polarizability_gradient_at_s is not None else None
    )
    if gaussian_aat_at_s is not None:
        if magnetic_dipole_derivatives is not None:
            raise ValueError("provide either modal magnetic derivatives or Gaussian AAT")
        omega_au = np.asarray(acquired_frequencies, dtype=float) / CM_PER_HARTREE
        if np.any(omega_au <= 0):
            raise ValueError("VCD requires positive harmonic frequencies")

        def momentum_coefficients(s: np.ndarray) -> np.ndarray:
            aat = np.asarray(gaussian_aat_at_s(s), dtype=float)
            if aat.shape != (3 * len(atoms), 3) or not np.all(np.isfinite(aat)):
                raise ValueError("Gaussian AAT must have finite 3N x 3 Cartesian entries")
            # The Gaussian AAT contracts nuclear velocity; qdot_i = omega_i p_i.
            return (2.0 / 137.035999084) * (
                aat.T @ tangent(np.asarray(s, dtype=float)) @ transform
            ) * omega_au[None, :]

        projected_momentum = _symmetry_project_property_jacobian(
            momentum_coefficients, dipole_symmetry_operations, n, 3, axial=True,
        )
        magnetic_dipole_derivatives = acquire_modal_momentum_derivatives_from_values(
            projected_momentum, transform, component_count=3,
            step_dimensionless=mode_steps,
            single_mode_only=quartic_policy != "complete",
        )
    if gaussian_roa_gradients_at_s is not None:
        if roa_response_derivatives is not None:
            raise ValueError("provide either modal ROA derivatives or Gaussian response gradients")
        if (roa_incident_frequency_au is None or not np.isfinite(roa_incident_frequency_au)
                or roa_incident_frequency_au <= 0):
            raise ValueError("Gaussian ROA acquisition requires an incident frequency")
        response_cache: dict[bytes, tuple[np.ndarray, np.ndarray, np.ndarray]] = {}

        def response(s: np.ndarray) -> tuple[np.ndarray, np.ndarray, np.ndarray]:
            displacement = np.asarray(s, dtype=float)
            key = np.ascontiguousarray(displacement).tobytes()
            if key not in response_cache:
                alpha, optical, dq = (
                    np.asarray(v, dtype=float) for v in gaussian_roa_gradients_at_s(displacement)
                )
                cart_count = 3 * len(atoms)
                if (alpha.shape != (cart_count, 3, 3)
                        or optical.shape != (cart_count, 3, 3)
                        or dq.shape != (cart_count, 3, 6)
                        or not all(np.all(np.isfinite(v)) for v in (alpha, optical, dq))):
                    raise ValueError("Gaussian ROA gradient tensors have invalid Cartesian dimensions")
                g_prime, a = gaussian_roa_response_tensors(
                    optical, dq, incident_frequency_au=roa_incident_frequency_au,
                )
                tangent_at_s = tangent(displacement)
                response_cache[key] = tuple(
                    value.reshape(cart_count, -1).T @ tangent_at_s
                    for value in (alpha, g_prime, a)
                )
            return response_cache[key]

        response_actions = (
            _symmetry_project_property_jacobian(
                lambda s, index=index: response(s)[index],
                dipole_symmetry_operations, n, count, rank=rank, axial=axial,
            )
            for index, count, rank, axial in (
                (0, 9, 2, False), (1, 9, 2, True), (2, 27, 3, False),
            )
        )
        alpha_response, g_response, a_response = response_actions
        alpha_s = acquire_modal_property_derivatives_from_gradients(
            alpha_response, transform, component_count=9,
            step_dimensionless=mode_steps,
            single_mode_only=quartic_policy != "complete",
        )
        g_s = acquire_modal_property_derivatives_from_gradients(
            g_response, transform, component_count=9,
            step_dimensionless=mode_steps,
            single_mode_only=quartic_policy != "complete",
        )
        a_s = acquire_modal_property_derivatives_from_gradients(
            a_response, transform, component_count=27,
            step_dimensionless=mode_steps,
            single_mode_only=quartic_policy != "complete",
        )
        roa_response_derivatives = SonicROAPropertySurfaces(
            alpha_s, g_s, a_s, roa_incident_frequency_au,
        )
    if polyad_selection_policy == "adaptive":
        def ir_observable(
            result: SonicGVPT2Result, seed: tuple[int, ...],
        ) -> dict[tuple[int, ...], float]:
            local = _component_spectrum_states(result, seed)
            evaluated = sonic_gvpt2_spectrum(
                local, dipole=dipole, field=acquired.field,
                transition_order="second",
            )
            return {state: float(np.real_if_close(evaluated.ir_intensities_km_mol[i]))
                    for i, state in enumerate(local.states) if state != local.states[0]}

        gvpt2 = solve_sonic_gvpt2_adaptive(
            acquired.field, target_max_quanta=polyad_target_max_quanta,
            seed_states=polyad_target_states,
            spectral_window_cm=polyad_spectral_window_cm,
            energy_tolerance_cm=polyad_energy_tolerance_cm,
            observable_tolerance=polyad_ir_tolerance_km_mol,
            observable=ir_observable, max_expansions=polyad_max_expansions,
            max_states=max_states, resonance_policy=resonance_policy,
            resonance_criteria=resonance_criteria,
            polyad_excluded_modes=polyad_excluded_modes,
            max_total_quanta=polyad_max_total_quanta,
            max_mode_quanta=polyad_max_mode_quanta,
            targeted_polyad_options=targeted_polyad_options,
        )
    assert gvpt2 is not None
    spectrum_result = (
        _fundamental_polyad_spectrum_states(gvpt2)
        if spectrum_state_policy == "fundamentals_polyads" else gvpt2
    )
    resolved_property_workers = resolve_sonic_property_workers(
        len(spectrum_result.frequencies_cm), len(spectrum_result.states),
        requested=property_workers,
    )
    spectrum = sonic_gvpt2_spectrum_parallel(
        spectrum_result, dipole=dipole, polarizability=polarizability,
        magnetic_dipole=magnetic_dipole_derivatives,
        roa_response=roa_response_derivatives,
        field=acquired.field, transition_order="second",
        workers=resolved_property_workers,
    )
    rovibrational = (
        acquire_sonic_rovibrational_constants(
            acquired, geometry_at_s=_eckart_geometry(geometry, masses, n),
            masses_amu=masses, rotational_dof=rotational_dof,
        ) if include_rovibrational else None
    )
    if harmonic_identity_required:
        # The ESALC-C reference is fixed by the same Cartesian H and D.
        cartesian_dipole = np.asarray(first.dipole_derivatives_au_per_bohr, dtype=float)
        if cartesian_dipole.shape != (3, 3 * len(atoms)):
            raise ValueError("harmonic ESALC-I/C gate requires a Cartesian dipole Jacobian")
        cartesian_frequencies, cartesian_modes = _eckart_projected_cartesian_modes(
            cart_hessian, reference_geometry, masses, rotational_dof,
        )
        gamma = np.sqrt(cartesian_frequencies * CM_PER_HARTREE) / HESSIAN_EIGENVALUE_TO_CM
        cartesian_first = cartesian_dipole @ (cartesian_modes / gamma)
        cartesian_ir = 0.5 * IR_TRANSITION_FACTOR * cartesian_frequencies * np.sum(
            cartesian_first**2, axis=0,
        )
        internal_ir = 0.5 * IR_TRANSITION_FACTOR * acquired_frequencies * np.sum(
            np.asarray(dipole.first)**2, axis=0,
        )
        frequency_residual = float(np.max(abs(
            np.sort(acquired_frequencies) - cartesian_frequencies,
        )))
        ir_residual = float(np.max(abs(
            internal_ir[np.argsort(acquired_frequencies)] - cartesian_ir,
        )))
        acquired.acquisition["harmonic_esalci_esalcc_frequency_residual_cm"] = frequency_residual
        acquired.acquisition["harmonic_esalci_esalcc_ir_residual_km_mol"] = ir_residual
        if frequency_residual > 0.01 or ir_residual > 0.01:
            raise ValueError(
                "harmonic ESALC-I/C identity failed after Eckart alignment: "
                f"frequency={frequency_residual:.6g} cm-1, "
                f"IR={ir_residual:.6g} km/mol"
            )
    return ESALCIGVPT2ProtocolResult(
        harmonic_gf, acquired, dipole, gvpt2, spectrum, len(cache), residual,
        polarizability, rovibrational, resolved_property_workers,
        SONIC_PROPERTY_WORKER_POLICY,
    )


def run_esalci_gvpt2_single_mode_protocol(**kwargs: object) -> ESALCIGVPT2ProtocolResult:
    """KeyMaker v2: acquire only derivatives accessible by one-mode shifts."""
    options = dict(kwargs)
    if options.pop("quartic_policy", "semidiagonal") != "semidiagonal":
        raise ValueError("single-mode protocol requires semidiagonal quartic coverage")
    options.setdefault("resonance_policy", "fermi_auto")
    return run_esalci_gvpt2_protocol(**options, quartic_policy="semidiagonal")


def run_esalci_gvpt2_analytic_metric_protocol(**kwargs: object) -> ESALCIGVPT2ProtocolResult:
    """Single-mode Hessians and dipoles; analytic G' gives complete G''."""
    options = dict(kwargs)
    if options.pop("quartic_policy", "semidiagonal_analytic_metric") != "semidiagonal_analytic_metric":
        raise ValueError("analytic-metric protocol requires semidiagonal quartic coverage")
    options.setdefault("resonance_policy", "fermi_auto")
    return run_esalci_gvpt2_protocol(**options, quartic_policy="semidiagonal_analytic_metric")


def run_esalci_gvpt2_smith_metric_protocol(
    *, smith_definition: object, **kwargs: object,
) -> ESALCIGVPT2ProtocolResult:
    """KeyMaker v4: obtain analytic B/B' from a frozen SMITH definition.

    The resident sparse B' implementation currently lives in matrix-zaff.
    Its numerical fallback list must be empty at every stencil point.
    """
    from matrix_smith import GICDefinition, build_gic_b_matrix
    from matrix_zaff.bmatrix_derivative import build_sparse_gic_b_matrix_derivative

    if not isinstance(smith_definition, GICDefinition):
        raise TypeError("analytic SMITH metric requires a frozen GICDefinition")
    options = dict(kwargs)
    if options.pop("quartic_policy", "semidiagonal_analytic_metric") != "semidiagonal_analytic_metric":
        raise ValueError("SMITH analytic-metric protocol requires semidiagonal quartic coverage")
    if any(options.get(name) is not None for name in (
        "metric_first_at_s", "b_matrix_at_s", "b_prime_cartesian_at_s",
    )):
        raise ValueError("SMITH analytic-metric protocol constructs its own B/B prime providers")
    geometry = options.get("geometry_at_s")
    frozen_b = np.asarray(options.get("frozen_esalci_b"), dtype=float)
    if not callable(geometry) or frozen_b.ndim != 2:
        raise ValueError("SMITH analytic-metric protocol requires a chart and frozen B")
    reference_angstrom = np.asarray(
        geometry(np.zeros(frozen_b.shape[0])), dtype=float,
    ) * BOHR_TO_ANGSTROM
    smith_reference_b = np.asarray(build_gic_b_matrix(
        smith_definition, coordinates_angstrom=reference_angstrom,
    ).rows, dtype=float)
    if smith_reference_b.shape != frozen_b.shape or np.linalg.matrix_rank(smith_reference_b) != len(frozen_b):
        raise ValueError("SMITH B has incompatible rank or shape")
    row_transform = frozen_b @ np.linalg.pinv(smith_reference_b)
    if not np.allclose(row_transform @ smith_reference_b, frozen_b,
                       rtol=1e-7, atol=1e-9):
        raise ValueError("SMITH B row space disagrees with the frozen ESALC-I chart")
    cache: dict[bytes, tuple[np.ndarray, np.ndarray]] = {}

    def derivatives(s: np.ndarray) -> tuple[np.ndarray, np.ndarray]:
        displacement = np.asarray(s, dtype=float)
        key = np.ascontiguousarray(displacement).tobytes()
        if key not in cache:
            xyz_bohr = np.asarray(geometry(displacement), dtype=float)
            xyz_angstrom = xyz_bohr * BOHR_TO_ANGSTROM
            b_angstrom = np.asarray(build_gic_b_matrix(
                smith_definition, coordinates_angstrom=xyz_angstrom,
            ).rows, dtype=float)
            derivative = build_sparse_gic_b_matrix_derivative(
                smith_definition, coordinates_angstrom=xyz_angstrom,
            )
            if derivative.numerical_fallback_primitives:
                raise ValueError(
                    "analytic SMITH B prime has numerical fallback primitives: "
                    + ", ".join(derivative.numerical_fallback_primitives)
                )
            b_bohr = row_transform @ b_angstrom
            b_prime_bohr2 = BOHR_TO_ANGSTROM * np.einsum(
                "ip,pab->iab", row_transform, derivative.to_dense(), optimize=True,
            )
            if b_bohr.shape != frozen_b.shape or b_prime_bohr2.shape != (
                frozen_b.shape[0], frozen_b.shape[1], frozen_b.shape[1]
            ):
                raise ValueError("SMITH B/B prime shape disagrees with frozen ESALC-I chart")
            if not options.get("analytic_eckart_chart") or not np.any(displacement):
                tangent_step = float(options.get("geometry_derivative_step_s", 1e-4))
                if not np.isfinite(tangent_step) or tangent_step <= 0:
                    raise ValueError("SMITH metric requires a positive chart derivative step")
                tangent = np.column_stack([
                    ((np.asarray(geometry(displacement + tangent_step * np.eye(len(frozen_b))[k]))
                      - np.asarray(geometry(displacement - tangent_step * np.eye(len(frozen_b))[k])))
                     / (2 * tangent_step)).reshape(-1)
                    for k in range(len(frozen_b))
                ])
                if not np.allclose(b_bohr @ tangent, np.eye(len(frozen_b)),
                                   rtol=1e-4, atol=1e-4):
                    raise ValueError("SMITH B and displaced ESALC-I chart disagree")
            cache[key] = b_bohr, b_prime_bohr2
        return cache[key]

    if not np.allclose(derivatives(np.zeros(frozen_b.shape[0]))[0], frozen_b,
                       rtol=1e-7, atol=1e-9):
        raise ValueError("SMITH B rows disagree with the frozen ESALC-I B matrix")
    options["b_matrix_at_s"] = lambda s: derivatives(s)[0]
    options["b_prime_cartesian_at_s"] = lambda s: derivatives(s)[1]
    options["eckart_full_metric_prime"] = bool(
        options.get("analytic_eckart_chart")
        and any(primitive.function == "SOOP" for primitive in smith_definition.primitives)
    )
    options.setdefault("resonance_policy", "fermi_auto")
    return run_esalci_gvpt2_protocol(
        **options, quartic_policy="semidiagonal_analytic_metric",
    )


def run_esalci_gvpt2_smith_metric_eckart_protocol(
    *, smith_definition: object, **kwargs: object,
) -> ESALCIGVPT2ProtocolResult:
    """KeyMaker v5: Eckart-normalized ESALC-I/C harmonic identity."""
    options = dict(kwargs)
    geometry = options.get("geometry_at_s")
    frozen_b = np.asarray(options.get("frozen_esalci_b"), dtype=float)
    if not callable(geometry) or frozen_b.ndim != 2:
        raise ValueError("Eckart protocol requires a frozen ESALC-I chart")
    options["geometry_at_s"] = _eckart_geometry(
        geometry, np.asarray(options["masses_amu"]), frozen_b.shape[0],
    )
    options["analytic_eckart_chart"] = True
    options["harmonic_identity_required"] = True
    return run_esalci_gvpt2_smith_metric_protocol(
        smith_definition=smith_definition, **options,
    )


def run_esalci_gvpt2_gdv_frame_protocol(
    *, smith_definition: object, fixed_cartesian_frame: bool = False,
    **kwargs: object,
) -> ESALCIGVPT2ProtocolResult:
    """KeyMaker v6: GDV displacement with one declared backend frame.

    A Cartesian electronic provider must return each derivative in the
    reference frame and certify coherent electronic integration grids across
    the stencil. Cartesian tensor transport alone is insufficient.
    """
    if fixed_cartesian_frame is not True:
        raise ValueError("GDV-frame protocol requires a fixed-frame Cartesian provider")
    options = dict(kwargs)
    requested_step = options.pop("step_mass_weighted_angstrom", None)
    if requested_step is not None and requested_step != 0.01:
        raise ValueError("GDV-frame protocol fixes the mass-weighted step at 0.01 angstrom")
    options["step_mass_weighted_angstrom"] = 0.01
    requested_cubic = options.pop("cubic_estimator_policy", None)
    if requested_cubic not in (None, "hessian_mean"):
        raise ValueError("GDV-frame protocol uses the Hessian-direction cubic mean")
    options["cubic_estimator_policy"] = "hessian_mean"
    return run_esalci_gvpt2_smith_metric_eckart_protocol(
        smith_definition=smith_definition, **options,
    )


