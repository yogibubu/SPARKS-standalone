def _eckart_geometry(
    geometry_at_s: Callable[[np.ndarray], np.ndarray], masses_amu: np.ndarray,
    coordinate_count: int,
) -> Callable[[np.ndarray], np.ndarray]:
    """Orient every internal-coordinate realization in the reference Eckart frame."""
    masses = np.asarray(masses_amu, dtype=float).reshape(-1)
    reference = np.asarray(geometry_at_s(np.zeros(coordinate_count)), dtype=float)
    if reference.shape != (len(masses), 3):
        raise ValueError("Eckart reference geometry has invalid shape")
    center = np.average(reference, axis=0, weights=masses)
    target = reference - center

    def aligned(displacement: np.ndarray) -> np.ndarray:
        xyz = np.asarray(geometry_at_s(np.asarray(displacement, dtype=float)), dtype=float)
        if xyz.shape != reference.shape or not np.all(np.isfinite(xyz)):
            raise ValueError("Eckart geometry must contain finite Cartesian coordinates")
        centered = xyz - np.average(xyz, axis=0, weights=masses)
        u, _, vt = np.linalg.svd((centered * masses[:, None]).T @ target)
        rotation = u @ np.diag((1.0, 1.0, np.linalg.det(u @ vt))) @ vt
        return centered @ rotation + center

    return aligned


def _eckart_projected_cartesian_modes(
    hessian: np.ndarray, geometry_bohr: np.ndarray, masses_amu: np.ndarray,
    rotational_dof: int,
) -> tuple[np.ndarray, np.ndarray]:
    """Diagonalize the vibrational Hessian in the rigid-free Eckart space."""
    xyz = np.asarray(geometry_bohr, dtype=float)
    masses = np.asarray(masses_amu, dtype=float)
    n = 3 * len(masses) - 3 - rotational_dof
    centered = xyz - np.average(xyz, axis=0, weights=masses)
    root_mass = np.sqrt(masses)[:, None]
    translations = [(root_mass * np.tile(axis, (len(masses), 1))).reshape(-1)
                    for axis in np.eye(3)]
    rotations = [(root_mass * np.cross(axis, centered)).reshape(-1)
                 for axis in np.eye(3)]
    rigid = np.column_stack(translations + rotations)
    basis, singular, _ = np.linalg.svd(rigid, full_matrices=True)
    rank = int(np.count_nonzero(singular > singular[0] * 1e-10))
    if rank != 3 + rotational_dof:
        raise ValueError("Eckart projection has unexpected rigid-body rank")
    vibrational_basis = basis[:, rank:]
    mass_cartesian = np.repeat(masses, 3)
    weighted = np.asarray(hessian, dtype=float) / np.sqrt(
        np.outer(mass_cartesian, mass_cartesian)
    )
    values, vectors = np.linalg.eigh(vibrational_basis.T @ weighted @ vibrational_basis)
    if len(values) != n or np.any(values <= 0):
        raise ValueError("projected Cartesian Hessian has a nonpositive vibrational mode")
    frequencies = np.sqrt(values) * HESSIAN_EIGENVALUE_TO_CM
    modes = (vibrational_basis @ vectors) / np.sqrt(mass_cartesian[:, None])
    return frequencies, modes


def _fundamental_polyad_spectrum_states(result: SonicGVPT2Result) -> SonicGVPT2Result:
    """Retain full variational polyads touching fundamentals for IR evaluation.

    External perturbative intermediate states are still generated by the
    spectroscopy contractions; this limits only requested output bands.
    """
    n = len(result.frequencies_cm)
    roots = tuple(range(n + 1))
    wanted = set(roots)
    changed = True
    while changed:
        before = len(wanted)
        for block in result.blocks:
            members = set(int(index) for index in block["indices"])
            if wanted & members:
                wanted.update(members)
        changed = len(wanted) != before
    selected = roots + tuple(sorted(wanted - set(roots)))
    mapping = {old: new for new, old in enumerate(selected)}
    blocks = tuple(
        dict(block, indices=tuple(mapping[int(index)] for index in block["indices"]))
        for block in result.blocks if set(block["indices"]) <= wanted
    )
    resonances = tuple(
        dict(item, i=mapping[int(item["i"])], j=mapping[int(item["j"])])
        for item in result.resonances
        if int(item["i"]) in mapping and int(item["j"]) in mapping
    )
    return replace(
        result,
        states=tuple(result.states[index] for index in selected),
        deperturbed_cm=np.asarray(result.deperturbed_cm)[list(selected)],
        energies_cm=np.asarray(result.energies_cm)[list(selected)],
        blocks=blocks,
        resonances=resonances,
    )


def _component_spectrum_states(
    result: SonicGVPT2Result, seed: tuple[int, ...],
) -> SonicGVPT2Result:
    """Keep one polyad and the ground state for its transition strengths."""
    seed_index = result.states.index(seed)
    members = next((tuple(int(i) for i in block["indices"])
                    for block in result.blocks if seed_index in block["indices"]),
                   (seed_index,))
    selected = tuple(sorted({0, *members}))
    mapping = {old: new for new, old in enumerate(selected)}
    blocks = tuple(
        dict(block, indices=tuple(mapping[int(i)] for i in block["indices"]))
        for block in result.blocks if set(block["indices"]) <= set(selected)
    )
    resonances = tuple(
        dict(item, i=mapping[int(item["i"])], j=mapping[int(item["j"])])
        for item in result.resonances
        if int(item["i"]) in mapping and int(item["j"]) in mapping
    )
    return replace(
        result,
        states=tuple(result.states[i] for i in selected),
        deperturbed_cm=np.asarray(result.deperturbed_cm)[list(selected)],
        energies_cm=np.asarray(result.energies_cm)[list(selected)],
        blocks=blocks,
        resonances=resonances,
    )


def dipole_derivatives_from_values(
    dipole_at_s: Callable[[np.ndarray], np.ndarray],
    displacement_per_q: np.ndarray,
    *, step_dimensionless: float = 0.12,
    single_mode_only: bool = False,
    symmetry_operations: tuple[tuple[np.ndarray, np.ndarray], ...] = (),
) -> SonicPropertyDerivatives:
    """D1/D2/D3 from dipole values in fixed modes.

    ``single_mode_only`` retains only derivatives obtainable from reference
    and plus/minus one-mode displacements (including plus/minus twice the step).
    """
    transform = np.asarray(displacement_per_q, dtype=float)
    if transform.ndim != 2 or transform.shape[0] != transform.shape[1]:
        raise ValueError("dipole-value stencil requires a square mode transform")
    n = len(transform)
    h = float(step_dimensionless)
    if not np.isfinite(h) or h <= 0:
        raise ValueError("dipole-value stencil step must be positive")
    operations = []
    for chart_action, vector_action in symmetry_operations:
        chart = np.asarray(chart_action, dtype=float)
        vector = np.asarray(vector_action, dtype=float)
        if (chart.shape != (n, n) or vector.shape != (3, 3)
                or not np.all(np.isfinite(chart)) or not np.all(np.isfinite(vector))
                or np.linalg.cond(chart) > 1e8
                or not np.allclose(vector.T @ vector, np.eye(3), atol=1e-8)):
            raise ValueError("dipole source symmetry actions must be valid linear maps")
        operations.append((chart, vector))
    cache: dict[tuple[int, ...], np.ndarray] = {}

    def source(displacement: np.ndarray) -> np.ndarray:
        value = np.asarray(dipole_at_s(displacement), dtype=float)
        if value.shape != (3,) or not np.all(np.isfinite(value)):
            raise ValueError("dipole provider must return three finite atomic-unit components")
        return value

    def value(shifts: tuple[int, ...]) -> np.ndarray:
        if shifts not in cache:
            displacement = h * transform @ np.asarray(shifts)
            dipole = source(displacement).copy()
            for chart, vector in operations:
                dipole += vector.T @ source(chart @ displacement)
            dipole /= 1 + len(operations)
            cache[shifts] = dipole
        return cache[shifts]

    zero = (0,) * n
    center = value(zero)
    first = np.zeros((3, n))
    second = np.zeros((3, n, n))
    third = np.zeros((3, n, n, n))

    def shifted(*terms: tuple[int, int]) -> np.ndarray:
        shifts = [0] * n
        for index, multiple in terms:
            shifts[index] += multiple
        return value(tuple(shifts))

    for i in range(n):
        plus, minus = shifted((i, 1)), shifted((i, -1))
        first[:, i] = (plus - minus) / (2 * h)
        second[:, i, i] = (plus - 2 * center + minus) / h**2
        third[:, i, i, i] = (
            shifted((i, 2)) - 2 * plus + 2 * minus - shifted((i, -2))
        ) / (2 * h**3)
    if not single_mode_only:
        for i, j in combinations(range(n), 2):
            second[:, i, j] = second[:, j, i] = (
            shifted((i, 1), (j, 1)) - shifted((i, 1), (j, -1))
            - shifted((i, -1), (j, 1)) + shifted((i, -1), (j, -1))
        ) / (4 * h**2)
            for repeat, single in ((i, j), (j, i)):
                derivative = (
                shifted((repeat, 1), (single, 1))
                - 2 * shifted((single, 1))
                + shifted((repeat, -1), (single, 1))
                - shifted((repeat, 1), (single, -1))
                + 2 * shifted((single, -1))
                - shifted((repeat, -1), (single, -1))
            ) / (2 * h**3)
                for indices in set(permutations((repeat, repeat, single))):
                    third[(slice(None), *indices)] = derivative
        for i, j, k in combinations(range(n), 3):
            derivative = sum(
            signs[0] * signs[1] * signs[2]
            * shifted((i, signs[0]), (j, signs[1]), (k, signs[2]))
            for signs in product((-1, 1), repeat=3)
        ) / (8 * h**3)
            for indices in permutations((i, j, k)):
                third[(slice(None), *indices)] = derivative
    return SonicPropertyDerivatives(first, second, third)


def symmetry_project_dipole_jacobian(
    jacobian_at_s: Callable[[np.ndarray], np.ndarray],
    operations: tuple[tuple[np.ndarray, np.ndarray], ...],
    coordinate_count: int,
) -> Callable[[np.ndarray], np.ndarray]:
    """Project a polar-vector Jacobian at its electronic source points."""
    return _symmetry_project_property_jacobian(
        jacobian_at_s, operations, coordinate_count, 3,
    )


def _tensor_property_action(
    vector: np.ndarray, *, rank: int, axial: bool = False,
    voigt: bool = False,
) -> np.ndarray:
    """Real point-group action on a Cartesian property tensor."""
    action = np.asarray(vector, dtype=float)
    if voigt:
        if rank != 2:
            raise ValueError("Voigt action requires a rank-two tensor")
        pairs = ((0, 0), (0, 1), (1, 1), (0, 2), (1, 2), (2, 2))
        columns = []
        for i, j in pairs:
            basis = np.zeros((3, 3))
            basis[i, j] = basis[j, i] = 1.0
            rotated = action @ basis @ action.T
            columns.append([rotated[a, b] for a, b in pairs])
        result = np.asarray(columns).T
    else:
        result = action.copy()
        for _ in range(1, rank):
            result = np.kron(result, action)
    return np.linalg.det(action) * result if axial else result


def _symmetry_project_property_jacobian(
    jacobian_at_s: Callable[[np.ndarray], np.ndarray],
    operations: tuple[tuple[np.ndarray, np.ndarray], ...],
    coordinate_count: int, component_count: int,
    *, rank: int = 1, axial: bool = False, voigt: bool = False,
) -> Callable[[np.ndarray], np.ndarray]:
    """Average symmetry-related source derivatives before modal differences."""
    checked = []
    for chart_action, vector_action in operations:
        chart = np.asarray(chart_action, dtype=float)
        vector = np.asarray(vector_action, dtype=float)
        if (chart.shape != (coordinate_count, coordinate_count)
                or vector.shape != (3, 3)
                or not np.all(np.isfinite(chart)) or np.linalg.cond(chart) > 1e8
                or not np.allclose(vector.T @ vector, np.eye(3), atol=1e-8)):
            raise ValueError("property source symmetry actions must be valid linear maps")
        property_action = _tensor_property_action(
            vector, rank=rank, axial=axial, voigt=voigt,
        )
        if property_action.shape != (component_count, component_count):
            raise ValueError("property source action has incompatible rank")
        checked.append((chart, property_action))

    def projected(s: np.ndarray) -> np.ndarray:
        displacement = np.asarray(s, dtype=float)
        result = np.asarray(jacobian_at_s(displacement), dtype=float).copy()
        if result.shape != (component_count, coordinate_count) or not np.all(np.isfinite(result)):
            raise ValueError("property source Jacobian has invalid shape or nonfinite values")
        for chart, property_action in checked:
            image = np.asarray(jacobian_at_s(chart @ displacement), dtype=float)
            if image.shape != result.shape or not np.all(np.isfinite(image)):
                raise ValueError("symmetry-related property Jacobian is invalid")
            result += property_action.T @ image @ chart
        return result / (1 + len(checked))

    return projected


